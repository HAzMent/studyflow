python3 <<'PY'

from pathlib import Path


p =
    Path("server.js")


s =
    p.read_text()


# IMPORT AUTH ROUTER

if 'from "./auth-routes.js"' not in s:

    lines =
        s.splitlines()


    last_import =
        0


    for i,line in enumerate(lines):

        if line.startswith("import "):
            last_import = i


    lines.insert(
        last_import + 1,
        'import supabaseAuthRouter from "./auth-routes.js";'
    )


    s =
        "\n".join(lines)


# Mount BEFORE old JSON auth routes.
# cloudRouter is already mounted after express-session,
# so mounting directly before cloudRouter gives us a safe location.

mount = '''

/*
  Supabase-backed account routes.
  These are mounted before the old JSON routes,
  so Register/Login/Profile now use Postgres.
*/

app.use("/api", supabaseAuthRouter);

'''


if 'app.use("/api", supabaseAuthRouter);' not in s:

    marker =
        'app.use("/api/cloud", cloudRouter);'


    if marker in s:

        s =
            s.replace(
                marker,
                mount + "\n" + marker,
                1
            )

    else:

        # fallback: place before first existing auth route

        markers = [
            'app.post("/api/register"',
            "app.post('/api/register'"
        ]


        inserted =
            False


        for marker in markers:

            pos =
                s.find(marker)


            if pos != -1:

                s =
                    s[:pos] + \
                    mount + \
                    "\n" + \
                    s[pos:]


                inserted =
                    True

                break


        if not inserted:

            raise SystemExit(
                "Could not find safe place to mount Supabase auth."
            )


p.write_text(s)


print(
    "✅ server.js now uses Supabase account routes"
)

PY


