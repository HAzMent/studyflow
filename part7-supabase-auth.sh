router.get(
  "/me",

  async (req,res) => {

    if(!req.session?.userId){

      return res
        .status(401)
        .json({
          error:
            "Not logged in."
        });

    }


    const supabase =
      requireDatabase(res);


    if(!supabase){
      return;
    }


    try{

      const {
        data:user,
        error
      } =
        await supabase

        .from(
          "studyflow_users"
        )

        .select(
          "id,email,name,university,major"
        )

        .eq(
          "id",
          req.session.userId
        )

        .maybeSingle();


      if(error){
        throw error;
      }


      if(!user){

        req.session.destroy(
          () => {}
        );


        return res
          .status(401)
          .json({
            error:
              "Account no longer exists."
          });

      }


      res.json({
        user:
          publicUser(user)
      });


    }catch(error){

      console.error(
        "Supabase /me:",
        error
      );


      res
        .status(500)
        .json({
          error:
            error.message
        });

    }

  }
);


/* =========================================================
   PROFILE
========================================================= */

router.put(
  "/profile",

  async (req,res) => {

    if(!req.session?.userId){

      return res
        .status(401)
        .json({
          error:
            "Login required."
        });

    }


    const supabase =
      requireDatabase(res);


    if(!supabase){
      return;
    }


    const update = {

      updated_at:
        new Date()
        .toISOString()

    };


    if(
      typeof req.body?.name ===
      "string"
    ){

      update.name =
        req.body.name.trim();

    }


    if(
      typeof req.body?.university ===
      "string"
    ){

      update.university =
        req.body.university.trim();

    }


    if(
      typeof req.body?.major ===
      "string"
    ){

      update.major =
        req.body.major.trim();

    }


    try{

      const {
        data:user,
        error
      } =
        await supabase

        .from(
          "studyflow_users"
        )

        .update(update)

        .eq(
          "id",
          req.session.userId
        )

        .select(
          "id,email,name,university,major"
        )

        .single();


      if(error){
        throw error;
      }


      res.json({
        user:
          publicUser(user)
      });


    }catch(error){

      console.error(
        "Profile update:",
        error
      );


      res
        .status(500)
        .json({
          error:
            error.message ||
            "Profile update failed."
        });

    }

  }
);


export default router;

EOF


