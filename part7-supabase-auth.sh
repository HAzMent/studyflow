cat > auth-routes.js <<'EOF'

import express from "express";
import bcrypt from "bcryptjs";

import {
  createClient
} from "@supabase/supabase-js";


const router =
  express.Router();


function getSupabase(){

  const url =
    process.env.SUPABASE_URL;

  const secret =
    process.env.SUPABASE_SECRET_KEY
    ||
    process.env.SUPABASE_SERVICE_ROLE_KEY;


  if(!url || !secret){
    return null;
  }


  return createClient(
    url,
    secret,
    {
      auth:{
        persistSession:false,
        autoRefreshToken:false
      }
    }
  );

}


function cleanEmail(value){

  return String(value || "")
    .trim()
    .toLowerCase();

}


function publicUser(user){

  return {

    id:user.id,

    email:user.email,

    name:user.name || "",

    university:user.university || "",

    major:user.major || ""

  };

}


function requireDatabase(res){

  const supabase =
    getSupabase();


  if(!supabase){

    res.status(503).json({
      error:
        "Supabase account storage is not configured."
    });

    return null;

  }


  return supabase;

}


/* =========================================================
   REGISTER
========================================================= */

router.post(
  "/register",

  async (req,res) => {

    const supabase =
      requireDatabase(res);


    if(!supabase){
      return;
    }


    const email =
      cleanEmail(req.body?.email);


    const password =
      String(
        req.body?.password || ""
      );


    const name =
      String(
        req.body?.name || ""
      ).trim();


    if(!email.includes("@")){

      return res
        .status(400)
        .json({
          error:
            "Enter a valid email address."
        });

    }


    if(password.length < 6){

      return res
        .status(400)
        .json({
          error:
            "Password must be at least 6 characters."
        });

    }


    try{

      const {
        data:existing,
        error:findError
      } =
        await supabase

        .from(
          "studyflow_users"
        )

        .select(
          "id"
        )

        .eq(
          "email",
          email
        )

        .maybeSingle();


      if(findError){
        throw findError;
      }


      if(existing){

        return res
          .status(409)
          .json({
            error:
              "An account with this email already exists."
          });

      }


      const password_hash =
        await bcrypt.hash(
          password,
          12
        );


      const {
        data:user,
        error
      } =
        await supabase

        .from(
          "studyflow_users"
        )

        .insert({

          email,

          password_hash,

          name:
            name ||
            email.split("@")[0],

          university:"",

          major:""

        })

        .select(
          "id,email,name,university,major"
        )

        .single();


      if(error){
        throw error;
      }


      req.session.userId =
        user.id;


      req.session.save(
        () => {

          res.json({
            user:
              publicUser(user)
          });

        }
      );


    }catch(error){

      console.error(
        "Supabase register:",
        error
      );


      res
        .status(500)
        .json({
          error:
            error.message ||
            "Could not create account."
        });

    }

  }
);


/* =========================================================
   LOGIN
========================================================= */

router.post(
  "/login",

  async (req,res) => {

    const supabase =
      requireDatabase(res);


    if(!supabase){
      return;
    }


    const email =
      cleanEmail(
        req.body?.email
      );


    const password =
      String(
        req.body?.password || ""
      );


    try{

      const {
        data:user,
        error
      } =
        await supabase

        .from(
          "studyflow_users"
        )

        .select(
          "id,email,password_hash,name,university,major"
        )

        .eq(
          "email",
          email
        )

        .maybeSingle();


      if(error){
        throw error;
      }


      if(!user){

        return res
          .status(401)
          .json({
            error:
              "Incorrect email or password."
          });

      }


      const valid =
        await bcrypt.compare(
          password,
          user.password_hash
        );


      if(!valid){

        return res
          .status(401)
          .json({
            error:
              "Incorrect email or password."
          });

      }


      req.session.userId =
        user.id;


      req.session.save(
        () => {

          res.json({
            user:
              publicUser(user)
          });

        }
      );


    }catch(error){

      console.error(
        "Supabase login:",
        error
      );


      res
        .status(500)
        .json({
          error:
            error.message ||
            "Login failed."
        });

    }

  }
);


