import express from "express";

import bcrypt from "bcryptjs";

import crypto from "crypto";

import {
  createClient
} from "@supabase/supabase-js";

import {
  Resend
} from "resend";


const router =
  express.Router();


function getSupabase(){

  const url =
    process.env.SUPABASE_URL;


  const secret =
    process.env.SUPABASE_SECRET_KEY
    ||
    process.env.SUPABASE_SERVICE_ROLE_KEY;


  if(
    !url ||
    !secret
  ){

    return null;

  }


  return createClient(
    url,
    secret,
    {

      auth:{

        persistSession:false,

        autoRefreshToken:false

      }

    }
  );

}


function normalizeEmail(value){

  return String(
    value || ""
  )
  .trim()
  .toLowerCase();

}


function createRawToken(){

  return crypto
    .randomBytes(32)
    .toString("hex");

}


function hashToken(token){

  return crypto
    .createHash("sha256")
    .update(token)
    .digest("hex");

}


function appUrl(req){

  return (
    process.env.APP_URL
    ||
    `${req.protocol}://${req.get("host")}`
  )
  .replace(/\/$/,"");

}


async function saveToken(
  supabase,
  userId,
  type,
  hours
){

  /*
    Remove older unused tokens
    of the same type.
  */

  await supabase

    .from(
      "studyflow_auth_tokens"
    )

    .delete()

    .eq(
      "user_id",
      userId
    )

    .eq(
      "token_type",
      type
    )

    .is(
      "used_at",
      null
    );


  const rawToken =
    createRawToken();


  const tokenHash =
    hashToken(
      rawToken
    );


  const expires =
    new Date(
      Date.now()
      +
      hours *
      60 *
      60 *
      1000
    );


  const {
    error
  } =
    await supabase

    .from(
      "studyflow_auth_tokens"
    )

    .insert({

      user_id:
        userId,

      token_hash:
        tokenHash,

      token_type:
        type,

      expires_at:
        expires.toISOString()

    });


  if(error){

    throw error;

  }


  return rawToken;

}


async function sendStudyFlowEmail({

  to,
  subject,
  html

}){

  const apiKey =
    process.env.RESEND_API_KEY;


  const from =
    process.env.RESEND_FROM_EMAIL;


  if(
    !apiKey ||
    !from
  ){

    return false;

  }


  const resend =
    new Resend(
      apiKey
    );


  const {
    error
  } =
    await resend.emails.send({

      from,

      to,

      subject,

      html

    });


  if(error){

    console.error(
      "Email error:",
      error
    );


    return false;

  }


  return true;

}


