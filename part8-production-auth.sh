python3 <<'PY'

from pathlib import Path


p = Path(
    "server.js"
)

s = p.read_text()


# ---------------------------------------------------------
# IMPORTS
# ---------------------------------------------------------

imports = [
    'import { createSessionMiddleware } from "./session-config.js";',
    'import authExtraRouter from "./auth-extra-routes.js";'
]


lines =
    s.splitlines()


for import_line in imports:

    if import_line not in s:

        last_import =
            max(
                [
                    i
                    for i,line
                    in enumerate(lines)
                    if line.startswith("import ")
                ],
                default=-1
            )


        lines.insert(
            last_import + 1,
            import_line
        )


        s =
            "\n".join(lines)


        lines =
            s.splitlines()


# ---------------------------------------------------------
# REPLACE EXPRESS SESSION MIDDLEWARE
# ---------------------------------------------------------

if "app.use(createSessionMiddleware());" not in s:

    start =
        s.find(
            "app.use(session("
        )


    if start != -1:

        depth =
            0


        i =
            start


        found_open =
            False


        while i < len(s):

            char =
                s[i]


            if char == "(":

                depth += 1

                found_open =
                    True


            elif char == ")":

                depth -= 1


                if (
                    found_open
                    and depth == 0
                ):

                    end =
                        i + 1


                    while (
                        end < len(s)
                        and s[end]
                        in " \t\r\n;"
                    ):

                        end += 1


                    s = (
                        s[:start]
                        +
                        "app.use(createSessionMiddleware());\n\n"
                        +
                        s[end:]
                    )


                    break


            i += 1

    else:

        marker =
            "app.use(express.json"


        pos =
            s.find(marker)


        if pos != -1:

            line_end =
                s.find(
                    "\n",
                    pos
                )


            s = (
                s[:line_end + 1]
                +
                "\napp.use(createSessionMiddleware());\n"
                +
                s[line_end + 1:]
            )


# ---------------------------------------------------------
# EXTRA AUTH ROUTER
# ---------------------------------------------------------

mount_line =
    'app.use("/api", authExtraRouter);'


if mount_line not in s:

    marker =
        'app.use("/api/cloud", cloudRouter);'


    if marker in s:

        s =
            s.replace(
                marker,
                mount_line
                +
                "\n\n"
                +
                marker,
                1
            )

    else:

        marker =
            'app.use("/api", supabaseAuthRouter);'


        if marker in s:

            s =
                s.replace(
                    marker,
                    marker
                    +
                    "\n"
                    +
                    mount_line,
                    1
                )


# ---------------------------------------------------------
# PASSWORD PAGES
# ---------------------------------------------------------

page_routes = r'''

app.get("/forgot-password", (req, res) => {

  res.sendFile(
    "forgot-password.html",
    {
      root:"public"
    }
  );

});


app.get("/reset-password", (req, res) => {

  res.sendFile(
    "reset-password.html",
    {
      root:"public"
    }
  );

});

'''


if 'app.get("/forgot-password"' not in s:

    static_marker =
        'app.use(express.static("public"));'


    if static_marker in s:

        s =
            s.replace(
                static_marker,
                page_routes
                +
                "\n"
                +
                static_marker,
                1
            )


p.write_text(s)


print(
    "✅ server.js production auth installed"
)

PY


