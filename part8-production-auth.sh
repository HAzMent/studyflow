router.post(
  "/reset-password",

  async (req,res) => {

    const supabase =
      getSupabase();


    if(!supabase){

      return res
        .status(503)
        .json({

          error:
            "Authentication service unavailable."

        });

    }


    const token =
      String(
        req.body?.token ||
        ""
      );


    const password =
      String(
        req.body?.password ||
        ""
      );


    if(password.length < 8){

      return res
        .status(400)
        .json({

          error:
            "Password must be at least 8 characters."

        });

    }


    if(!token){

      return res
        .status(400)
        .json({

          error:
            "Reset token is missing."

        });

    }


    try{

      const tokenHash =
        hashToken(
          token
        );


      const {
        data:record,
        error
      } =
        await supabase

        .from(
          "studyflow_auth_tokens"
        )

        .select(
          "id,user_id,expires_at,used_at"
        )

        .eq(
          "token_hash",
          tokenHash
        )

        .eq(
          "token_type",
          "reset_password"
        )

        .maybeSingle();


      if(error){

        throw error;

      }


      if(
        !record ||
        record.used_at ||
        new Date(
          record.expires_at
        ).getTime() <
        Date.now()
      ){

        return res
          .status(400)
          .json({

            error:
              "This password reset link is invalid or has expired."

          });

      }


      const passwordHash =
        await bcrypt.hash(
          password,
          12
        );


      const {
        error:updateError
      } =
        await supabase

        .from(
          "studyflow_users"
        )

        .update({

          password_hash:
            passwordHash,

          updated_at:
            new Date()
            .toISOString()

        })

        .eq(
          "id",
          record.user_id
        );


      if(updateError){

        throw updateError;

      }


      await supabase

        .from(
          "studyflow_auth_tokens"
        )

        .update({

          used_at:
            new Date()
            .toISOString()

        })

        .eq(
          "id",
          record.id
        );


      /*
        Remove other reset tokens.
      */

      await supabase

        .from(
          "studyflow_auth_tokens"
        )

        .delete()

        .eq(
          "user_id",
          record.user_id
        )

        .eq(
          "token_type",
          "reset_password"
        )

        .neq(
          "id",
          record.id
        );


      return res.json({

        success:true,

        message:
          "Password changed successfully."

      });


    }catch(error){

      console.error(
        "Reset password:",
        error
      );


      return res
        .status(500)
        .json({

          error:
            "Could not reset password."

        });

    }

  }
);


